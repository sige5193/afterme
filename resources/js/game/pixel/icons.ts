export function faceIcon(i: number, color = false): Canvas {
  const rows = FACE_BASE.map((r) => r.split(''));
  const clown = i === 4;
  if (clown) {
    for (const row of rows) for (let x = 0; x < row.length; x++) if (row[x] === 'f' || row[x] === 'F') row[x] = 'w';
  }
  for (const [x, y, c] of FACE_MARKS[i] ?? FACE_MARKS[0]) {
    if (rows[y] && x < 16) rows[y][x] = c;
  }
  const canvas = fromArt(rows.map((r) => r.join('')), P);
  return color ? canvas : grayscale(canvas, 1.15);
}

/** 遗像：黑框 + 黑纱，24×28 */
export function portraitFrame(i: number): Canvas {
  const c = makeCanvas(24, 28);
  const x = ctx2d(c);
  x.fillStyle = C.out;
  x.fillRect(0, 2, 24, 26);
  x.fillStyle = '#2b2733';
  x.fillRect(1, 3, 22, 24);
  x.fillStyle = '#d9d5cc';
  x.fillRect(3, 5, 18, 20);
  x.drawImage(faceIcon(i), 4, 7);
  // 黑纱花
  x.fillStyle = C.out;
  x.fillRect(9, 0, 6, 4);
  x.fillRect(7, 1, 2, 2);
  x.fillRect(15, 1, 2, 2);
  x.fillStyle = '#3a3640';
  x.fillRect(10, 1, 4, 2);
  return c;
}

